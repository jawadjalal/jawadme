"""Outlines for the display arena: "design mastermind" as SVG paths, 1000 units to the em, baseline at 0, y down.
a and b are the shaped face (HarfBuzz, the font's own kerning); c is lettered on Geist's skeleton.
Needs fonttools, uharfbuzz and skia-pathops. Run from outside this folder:
  python -P src/components/ds/display/outline.py GeistSerif-Square.woff2 Excalifont-Regular.woff2 Geist-Variable.woff2 src/components/ds/display
The sources are the full fonts (geist 1.9.2 on npm; excalidraw/excalidraw packages/excalidraw/fonts/Excalifont)."""
import io, json, math, sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen, RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
import uharfbuzz as hb
import pathops

WORDS = ["design", "mastermind"]


def load(path):
    f = TTFont(path)
    f.flavor = None
    b = io.BytesIO()
    f.save(b)
    return f, hb.Font(hb.Face(hb.Blob(b.getvalue())))


def shape(hbf, text, loc=None, feats=None):
    if loc:
        hbf.set_variations(loc)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hbf, buf, feats or {})
    return [(i.codepoint, p.x_advance, p.x_offset) for i, p in zip(buf.glyph_infos, buf.glyph_positions)]


def record(gs, name):
    r = DecomposingRecordingPen(gs)
    gs[name].draw(r)
    return r.value


def to_path(rec, dx=0.0):
    p = pathops.Path()
    pen = p.getPen()
    for op, pts in rec:
        getattr(pen, op)(*[None if q is None else (q[0] + dx, q[1]) for q in pts])
    return p


def union(paths):
    out = pathops.Path()
    for p in paths:
        out = pathops.op(out, p, pathops.PathOp.UNION) if len(list(out.segments)) else p
    out.simplify()
    return out


def svg(path):
    rec = RecordingPen()
    path.draw(rec)
    pen = SVGPathPen(None, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    for op, pts in rec.value:
        getattr(pen, op)(*[None if q is None else (q[0], -q[1]) for q in pts])
    return pen.getCommands()


def bounds(paths):
    bs = [p.bounds for p in paths if len(list(p.segments))]
    return min(b[0] for b in bs), min(b[1] for b in bs), max(b[2] for b in bs), max(b[3] for b in bs)


def face_set(path, loc=None, feats=None, track=0):
    f, hbf = load(path)
    gs = f.getGlyphSet(location=loc) if loc else f.getGlyphSet()
    words = []
    for t in WORDS:
        x = 0
        g = []
        for gid, adv, off in shape(hbf, t, loc, feats):
            g.append(union([to_path(record(gs, f.getGlyphOrder()[gid]), x + off)]))
            x += adv + track
        words.append({"t": t, "w": x - track, "g": g})
    return words


def emit(words, out, const):
    lo = bounds([p for w in words for p in w["g"]])
    asc = math.ceil(max(750, lo[3] + 20) / 10) * 10
    desc = math.ceil(max(250, -lo[1] + 20) / 10) * 10
    data = [{"t": w["t"], "w": round(max(w["w"], bounds(w["g"])[2] + 20)), "g": [svg(p) for p in w["g"]]} for w in words]
    with open(out, "w") as fh:
        fh.write("// Generated by outline.py. Do not edit by hand.\nimport type { Mark } from \"./mark\";\n\nexport const %s: Mark = { asc: %d, desc: %d, words: %s };\n" % (const, asc, desc, json.dumps(data, separators=(",", ":"))))
    return asc, desc


def contrast(f, hbf, t, heavy, light, theta, track):
    """Geist at two weights, mixed per point along a tilted pen: the stroke across the nib from the heavy master, the
    stroke along it from the light one, so stems stay full and joins and horizontals thin out (ink weight variation)."""
    c, s = math.cos(math.radians(theta)), math.sin(math.radians(theta))
    gh = f.getGlyphSet(location={"wght": heavy})
    gl = f.getGlyphSet(location={"wght": light})
    x = 0
    out = []
    for gid, adv, off in shape(hbf, t, {"wght": heavy}):
        name = f.getGlyphOrder()[gid]
        rh, rl = record(gh, name), record(gl, name)
        shift = (gh.hMetrics[name][0] - gl.hMetrics[name][0]) / 2
        rec = []
        for (op, ph), (_, pl) in zip(rh, rl):
            pts = []
            for qh, ql in zip(ph, pl):
                if qh is None:
                    pts.append(None)
                    continue
                xl, yl = ql[0] + shift, ql[1]
                dx, dy = qh[0] - xl, qh[1] - yl
                u = dx * c + dy * s
                pts.append((xl + u * c, yl + u * s))
            rec.append((op, pts))
        out.append({"name": name, "x": x + off, "adv": adv, "rec": rec})
        x += adv + track
    return out, x - track


def bez(c, t):
    m = 1 - t
    return tuple(m * m * m * c[0][k] + 3 * m * m * t * c[1][k] + 3 * m * t * t * c[2][k] + t * t * t * c[3][k] for k in (0, 1))


def dbez(c, t):
    m = 1 - t
    return tuple(3 * m * m * (c[1][k] - c[0][k]) + 6 * m * t * (c[2][k] - c[1][k]) + 3 * t * t * (c[3][k] - c[2][k]) for k in (0, 1))


def poly(pts):
    p = pathops.Path()
    pen = p.getPen()
    pen.moveTo(pts[0])
    for q in pts[1:]:
        pen.lineTo(q)
    pen.closePath()
    p.simplify()
    return p


def nib(ctrl, a, b, env, n=72):
    """A stroke drawn with an elliptical nib (half-width a across, half-height b): upright travel lays the full stem,
    level travel a hairline, the same contrast the letters carry. env(t) scales the nib, for the pressure and the lifts."""
    left, right = [], []
    for i in range(n + 1):
        t = i / n
        (px, py), (tx, ty) = bez(ctrl, t), dbez(ctrl, t)
        l = math.hypot(tx, ty) or 1e-9
        nx, ny = -ty / l, tx / l
        d = math.sqrt(a * a * nx * nx + b * b * ny * ny) or 1e-9
        k = env(t)
        ox, oy = a * a * nx / d * k, b * b * ny / d * k
        left.append((px + ox, py + oy))
        right.append((px - ox, py - oy))
    return poly(left + right[::-1])


def drop(cx, cy, r, tip, angle, n=40):
    """An ink drop: a round with its tail flicked out toward angle (degrees), tip units from the centre."""
    phi = math.radians(angle)
    t0 = math.acos(r / tip)
    pts = [(cx + tip * math.cos(phi), cy + tip * math.sin(phi))]
    for i in range(n + 1):
        th = phi + t0 + (2 * math.pi - 2 * t0) * i / n
        pts.append((cx + r * math.cos(th), cy + r * math.sin(th)))
    return poly(pts)


def rect(x0, y0, x1, y1):
    return poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)])


def lift(t0=0.0, t1=1.0, a=0.18, b=0.3, floor=0.04, swell=0.0):
    """Pressure along a stroke: rises over the first a, swells by swell in the middle, falls to floor over the last b."""
    def env(t):
        u = (t - t0) / (t1 - t0)
        k = 1.0
        if a and u < a:
            k = floor + (1 - floor) * math.sin(u / a * math.pi / 2)
        if b and u > 1 - b:
            k = min(k, floor + (1 - floor) * math.sin((1 - u) / b * math.pi / 2))
        return k * (1 + swell * math.sin(u * math.pi))
    return env


A, B = 92, 31


def lettered(path, heavy=850, light=300, track=-6):
    """Option c: Geist's skeleton with an upright broad-nib contrast, the drawn pieces unioned into the letters that own
    them: an st ligature over the t, a g whose tail runs back under the word, an r that joins the m, a d that lifts off,
    ink drops for tittles and a pen-entry spur on every stem that starts at the x-height."""
    f, hbf = load(path)
    words = []
    for t in WORDS:
        gl, w = contrast(f, hbf, t, heavy, light, 0, track)
        X = [g["x"] for g in gl]
        add = {i: [] for i in range(len(t))}
        cut = {i: [] for i in range(len(t))}
        for i, ch in enumerate(t):
            x = X[i]
            if ch in "mnri" and not (t == "mastermind" and i == 6):
                cut[i].append(poly([(x + 20, 499), (x + 232, 566), (x + 232, 700), (x + 20, 700)]))
                add[i].append(poly([(x + 58, 420), (x + 28, 502), (x + 232, 566), (x + 232, 420)]))
            if ch == "i":
                cut[i].append(rect(x + 20, 600, x + 280, 740))
                add[i].append(drop(x + 150, 676, 82, 150, 58))
            if ch == "d" and i == len(t) - 1:
                add[i].append(nib(((x + 503, 90), (x + 505, -50), (x + 690, -44), (x + 820, 70)), A, B, lift(a=0, b=0.6, floor=0.02)))
            if ch == "d":
                cut[i].append(rect(x + 400, 640, x + 620, 760))
                add[i].append(poly([(x + 412, 600), (x + 382, 682), (x + 595, 742), (x + 595, 600)]))
        if t == "design":
            g = 4
            x = X[g]
            cut[g].append(rect(x - 40, -260, x + 640, 12))
            add[g].append(nib(((x + 504, 40), (x + 504, -112), (x + 400, -153), (x + 230, -157)), A, B, lambda u: 1))
            add[g].append(nib(((x + 262, -156), (x - 200, -162), (x - 900, -170), (x - 1350, -40)), A, B, lift(a=0, b=0.7, floor=0.0, swell=0.35)))
        else:
            s, tt, r, m = 2, 3, 5, 6
            xs, xt = X[s], X[tt]
            cut[tt].append(rect(xt + 100, 560, xt + 330, 700))
            add[tt].append(nib(((xs + 330, 515), (xs + 470, 790), (xt + 215, 830), (xt + 215, 540)), A, B, lambda u: 0.3 + 0.7 * u ** 2.4))
            xr, xm = X[r], X[m]
            add[r].append(nib(((xr + 360, 498), (xr + 470, 498), (xm - 30, 530), (xm + 150, 502)), A, B, lift(a=0, b=0.0)))
        out = []
        for i, g in enumerate(gl):
            p = to_path(g["rec"], g["x"])
            for q in cut[i]:
                p = pathops.op(p, q, pathops.PathOp.DIFFERENCE)
            out.append(union([p] + add[i]))
        words.append({"t": t, "w": w, "g": out})
    return words


if __name__ == "__main__":
    serif, excali, geist, out = sys.argv[1:5]
    print("a", emit(face_set(serif, track=-8), out + "/a.ts", "A"))
    print("b", emit(face_set(excali, track=0), out + "/b.ts", "B"))
    print("c", emit(lettered(geist), out + "/c.ts", "C"))
